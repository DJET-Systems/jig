std::string q(const std::string& s) {
    std::string o = "\"";
    for (char c : s) {
        if (c == '"' || c == '\\') o.push_back('\\');
        o.push_back(c);
    }
    return o + "\"";
}

std::string join_q(const std::vector<std::string>& v, const std::string& indent = "  ") {
    std::string o;
    for (const auto& s : v) o += indent + q(s) + "\n";
    return o;
}

bool ends_with(const std::string& s, std::string_view suf) { return s.size() >= suf.size() && s.compare(s.size() - suf.size(), suf.size(), suf) == 0; }

std::string stem_of(const std::string& rel) {
    auto name = fs::path(rel).stem().string();
    return name;
}

